// New C++ program to display basic information in the console.
#include <iostream>
using namespace std;

int main() {
	// Declare First Name, Last Name, Street Address, City, and Zip code in console
	char firstName[] = "Mary";
	char lastName[] = "Smith";
	char streetAddress[] = "1234 Test Street";
	char city[] = "Fort Bend";
	int zipCode = 80123;

	// Display stored data in the console
	std::cout << "First Name: " << firstName << ",\n";
	std::cout << "Last Name: " << lastName << ",\n";
	std::cout << "Street Address: " << streetAddress << ",\n";
	std::cout << "City: " << city << ",\n";
	std::cout << "Zip code: " << zipCode << "\n";

	return 0;
}




